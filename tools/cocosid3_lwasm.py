#!/usr/bin/env python3
"""Make the author's cocosid3.asm assemble with lwasm, to the same bytes.

His assembler accepted a few things lwasm does not, and encoded one
instruction differently. This applies the smallest edits that fix that and
writes the result to stdout. Each edit is listed in EDITS and is checked to
apply exactly once.

usage: cocosid3_lwasm.py third-party/cocosid3/cocosid3.asm > cocosid3/cocosid3.asm
"""
import sys

EDITS = [
    # He wrote the DAC store with '#'; his assembler took it as extended.
    ("\tstb\t#$FF20\t", "\tstb\t$FF20\t"),
    ("\tsta\t#BORDERCOLOR\n", "\tsta\tBORDERCOLOR\n"),
    # Size guards whose bodies are deliberate syntax errors. lwasm rejects
    # the forward reference in the second one even when the test is false.
    ("\tif check_org_dp>=$1100\n"
     "\t\tProblem: code+data too big to fit in same page\n"
     "\tendif\n", ""),
    ("\tif ZZZLASTSYMBOL>$7E80\n"
     "\t\tDanger: code+data exceed safe limit. Bad thing could happen "
     "because of BASIC stack overwriting.\n"
     "\tendif\n", ""),
    # His assembler encodes 'std ssynth.freq,u' (offset 0) as 0,u, not ,u.
    ("\torg $1000\n", "\tpragma noindex0tonone\n\torg $1000\n"),
    # His assembler also emitted the three voice records, as zeros.
    ("synth3\t\tssynth\n",
     "synth3\t\tssynth\n\torg synth1\n\tzmb\t3*sizeof{ssynth}\n"),
]

HEADER = """\
; Generated by tools/cocosid3_lwasm.py from third-party/cocosid3/cocosid3.asm
; (Remi Veilleux, 2012). Edited only so that lwasm builds the same bytes;
; see that script for the list of edits. Song data: cocosid3/song/*.cid.

"""


def main(path):
    src = open(path, encoding="latin-1", newline="").read().replace("\r\n", "\n")
    for old, new in EDITS:
        n = src.count(old)
        if n != 1:
            sys.exit(f"edit applies {n} times, expected 1: {old!r}")
        src = src.replace(old, new)
    sys.stdout.write(HEADER + src)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
